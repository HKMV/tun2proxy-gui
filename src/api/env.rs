//! 运行环境：进程有没有管理员权限、能不能自己提权重启。
//!
//! 这两件事不属于任何一页（不是配置、不是隧道状态），但界面必须知道：
//! 没有管理员权限时隧道**一定起不来**，用户点「启动」只会看到一句看不懂的
//! 内核报错。所以把结论摆出来，并且给一条出路。
//!
//! 发布版（`src/main.rs`）在开窗口之前就 UAC 重启过自己，走不到这里；
//! 走 `nsh run` 的开发宿主和 `nsh package` 打出来的包没有那一步，所以界面
//! 得自己兜住。

/// 权限不够时的一句话，够用时是 `None`。
///
/// 文案写**后果**：用户看到「无法创建虚拟网卡」并不知道这意味着什么，所以
/// 那句话的后半截是「隧道起不来，系统流量照常直连，不会经过代理」。
pub fn privilege_hint() -> Option<String> {
    crate::core::elevate::privilege_hint()
}

/// 以管理员身份重新拉起自己。
///
/// 返回 `true` 时新进程已经起来了，**本进程应当立刻退出**（新进程会接手单实例
/// 与窗口）；`false` 表示用户取消了 UAC 或者拉起失败。
pub fn relaunch_elevated() -> bool {
    crate::core::elevate::relaunch_elevated()
}
